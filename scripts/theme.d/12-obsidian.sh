OBS_PURPLE=$(blend_hex "$ACCENT" "#bd93f9" 30)
OBS_BLUE=$(blend_hex "$ACCENT_DIM" "#8be9fd" 35)
OBS_SIDEBAR=$(blend_hex "$BG" "#000000" 18)

