#!/usr/bin/env bash

# ==========================================
# HP Pavilion 14-ce - Brightness + media keys (machine-specific)
# ==========================================
# Makes the brightness keys (F2 = dim, F3 = brighten) and media keys
# (F9 = previous, F10 = play/pause, F11 = next) work on this laptop.
# Only run this on the HP Pavilion; it lives outside ~/dotfiles on purpose.
#
# What it does:
#   1. Installs sxhkd (hotkey daemon), brightnessctl (backlight control)
#      and playerctl (controls Spotify, browsers and other MPRIS players).
#   2. Adds the current user to the 'video' group, which may write
#      /sys/class/backlight/*/brightness.
#   3. Writes ~/.config/sxhkd/sxhkdrc binding XF86MonBrightnessUp/Down to
#      brightnessctl in 10% steps (never below 1, so the screen never goes black)
#      and XF86AudioPrev/Play/Next to playerctl.
#   4. Writes ~/.config/autostart/sxhkd.desktop so sxhkd starts at login
#      (i3 runs 'dex --autostart', which picks it up).
#   5. (Re)starts sxhkd with the video group so it works without logging out.
#
# Safe to run more than once.

set -eu

echo "==> Installing sxhkd, brightnessctl and playerctl..."
sudo apt install -y sxhkd brightnessctl playerctl

echo "==> Adding $USER to the video group..."
sudo usermod -aG video "$USER"

echo "==> Writing ~/.config/sxhkd/sxhkdrc..."
mkdir -p "$HOME/.config/sxhkd"
cat > "$HOME/.config/sxhkd/sxhkdrc" <<'EOF'
# Machine-specific (HP Pavilion 14-ce) - generated by hp_pavillion_bightness_keys.sh
XF86MonBrightnessUp
    brightnessctl -q set +10%
XF86MonBrightnessDown
    brightnessctl -q --min-value=1 set 10%-
XF86AudioPrev
    playerctl previous
XF86AudioPlay
    playerctl play-pause
XF86AudioPause
    playerctl play-pause
XF86AudioNext
    playerctl next
EOF

echo "==> Writing ~/.config/autostart/sxhkd.desktop..."
mkdir -p "$HOME/.config/autostart"
cat > "$HOME/.config/autostart/sxhkd.desktop" <<'EOF'
[Desktop Entry]
Type=Application
Name=sxhkd
Exec=sxhkd
X-GNOME-Autostart-enabled=true
EOF

if [ -n "${DISPLAY:-}" ]; then
    echo "==> Restarting sxhkd with the video group..."
    pkill -x sxhkd || true
    sg video -c 'setsid -f sxhkd >/dev/null 2>&1'
else
    echo "==> No X session found; sxhkd will start at next login."
fi

echo "==> Done. Brightness and media keys should work now (or after logging in again)."
