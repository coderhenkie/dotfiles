#!/usr/bin/env bash
# ==========================================
# HP Pavilion 14-ce - Brightness + media keys (machine-specific)
# ==========================================
# Makes the brightness keys (F2 = dim, F3 = brighten) and media keys
# (F9 = previous, F10 = play/pause, F11 = next) work on this laptop.
# Lives in machines/ in the dotfiles repo; only run this on the HP Pavilion 14-ce.
#
# What it does:
#   1. Installs sxhkd (hotkey daemon), brightnessctl (backlight control)
#      and playerctl (controls Spotify, browsers and other MPRIS players).
#   2. Adds the current user to the 'video' group, which may write
#      /sys/class/backlight/*/brightness.
#   3. Writes ~/.config/sxhkd/sxhkdrc binding XF86MonBrightnessUp/Down to
#      brightnessctl in 10% steps (never below 1, so the screen never goes black)
#      and XF86AudioPrev/Play/Next to playerctl.
#   4. Writes ~/.config/autostart/sxhkd.desktop so sxhkd starts at login
#      (i3 runs 'dex --autostart', which picks it up).
#   5. (Re)starts sxhkd with the video group so it works without logging out.
#
# Usage: hp-pavilion-brightness-keys.sh [--force|-h|--help]
# Safe to run more than once.

set -euo pipefail

# shellcheck source-path=SCRIPTDIR source=../scripts/lib/common.sh
source "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")/../scripts/lib/common.sh"

case "${1:-}" in
    -h|--help) help_from_header; exit 0 ;;
esac

product_name=$(cat /sys/class/dmi/id/product_name 2>/dev/null || true)
if [[ ! "$product_name" =~ [Pp]avilion ]] && [ "${1:-}" != "--force" ]; then
    warn "Detected hardware '${product_name:-unknown}' does not look like an HP Pavilion."
    warn "This script is machine-specific for the HP Pavilion 14-ce."
    if [ -t 0 ]; then
        read -r -p "Continue anyway? [y/N]: " ans
        [[ "$ans" =~ ^[Yy]$ ]] || exit 1
    else
        die "Re-run with --force to override on non-Pavilion hardware."
    fi
fi

log "Installing sxhkd, brightnessctl and playerctl..."
if have nala; then
    sudo nala install -y sxhkd brightnessctl playerctl
else
    sudo apt install -y sxhkd brightnessctl playerctl
fi

target_user="${SUDO_USER:-${USER:-$(id -un)}}"
log "Adding $target_user to the video group..."
sudo usermod -aG video "$target_user"

log "Writing ~/.config/sxhkd/sxhkdrc..."
mkdir -p "$HOME/.config/sxhkd"
cat > "$HOME/.config/sxhkd/sxhkdrc" <<'EOF'
# Machine-specific (HP Pavilion 14-ce) - generated by machines/hp-pavilion-brightness-keys.sh
XF86MonBrightnessUp
    brightnessctl -q set +10%
XF86MonBrightnessDown
    brightnessctl -q --min-value=1 set 10%-
XF86AudioPrev
    playerctl previous
XF86AudioPlay
    playerctl play-pause
XF86AudioPause
    playerctl play-pause
XF86AudioNext
    playerctl next
EOF

log "Writing ~/.config/autostart/sxhkd.desktop..."
mkdir -p "$HOME/.config/autostart"
cat > "$HOME/.config/autostart/sxhkd.desktop" <<'EOF'
[Desktop Entry]
Type=Application
Name=sxhkd
Exec=sxhkd
X-GNOME-Autostart-enabled=true
EOF

if [ -n "${DISPLAY:-}" ]; then
    log "Restarting sxhkd with the video group..."
    pkill -x sxhkd || true
    sg video -c 'setsid -f sxhkd >/dev/null 2>&1'
else
    log "No X session found; sxhkd will start at next login."
fi

ok "Done. Brightness and media keys should work now (or after logging in again)."
