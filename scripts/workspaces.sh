#!/usr/bin/env bash
# ==========================================
# Workspace -> Screen Assignment
# ==========================================
# 1 screen (or mirrored): every workspace on that screen (no assignments).
# 2 screens side by side: workspaces 1-4 on the LEFT screen, 5-10 on the RIGHT screen.
# 3+ screens: not configured yet (no assignments, i3's default behaviour).
#
# Writes ~/.cache/theme/workspaces.conf (included by i3/config), reloads i3 only when that
# file changed, and moves already open workspaces to their screen. Run by i3 at startup,
# by the autorandr postswitch hook and by scripts/menu-monitors.sh.

set -u

CONF="$HOME/.cache/theme/workspaces.conf"
LEFT_WS=(1 2 3 4)
RIGHT_WS=(5 6 7 8 9 10)

command -v i3-msg >/dev/null 2>&1 && command -v jq >/dev/null 2>&1 || exit 0
i3-msg -t get_version >/dev/null 2>&1 || exit 0

# Serialize: postswitch and i3's exec_always can fire at the same time
exec 9>"${XDG_RUNTIME_DIR:-/tmp}/i3-workspaces.lock"
flock 9

# Active i3 outputs, left to right (mirrored screens count as one: i3 disables clones)
mapfile -t OUTS < <(i3-msg -t get_outputs | jq -r '[.[] | select(.active)] | sort_by(.rect.x, .rect.y) | .[].name')

NEW=$(
    echo "# Generated by ~/dotfiles/scripts/workspaces.sh: do not edit (re-generated on every screen change)"
    if [ "${#OUTS[@]}" -eq 2 ]; then
        for ws in "${LEFT_WS[@]}";  do echo "workspace $ws output ${OUTS[0]}"; done
        for ws in "${RIGHT_WS[@]}"; do echo "workspace $ws output ${OUTS[1]}"; done
    fi
)

mkdir -p "$(dirname "$CONF")"
if [ "$NEW" != "$(cat "$CONF" 2>/dev/null)" ]; then
    printf '%s\n' "$NEW" > "$CONF"
    i3-msg reload >/dev/null
fi

[ "${#OUTS[@]}" -eq 2 ] || exit 0

# Move open workspaces that are on the wrong screen, then restore what was visible/focused
target_of() {
    local ws=$1 w
    for w in "${LEFT_WS[@]}";  do [ "$w" = "$ws" ] && { echo "${OUTS[0]}"; return; }; done
    for w in "${RIGHT_WS[@]}"; do [ "$w" = "$ws" ] && { echo "${OUTS[1]}"; return; }; done
}

WS_JSON=$(i3-msg -t get_workspaces)
FOCUSED=$(jq -r '.[] | select(.focused) | .name' <<< "$WS_JSON")
mapfile -t VISIBLE < <(jq -r '.[] | select(.visible) | .name' <<< "$WS_JSON")
moved=0

while IFS=$'\t' read -r num name output; do
    target=$(target_of "$num")
    [ -n "$target" ] && [ "$output" != "$target" ] || continue
    i3-msg -q "workspace --no-auto-back-and-forth \"$name\"; move workspace to output $target"
    moved=1
done < <(jq -r '.[] | [.num, .name, .output] | @tsv' <<< "$WS_JSON")

if [ "$moved" = 1 ]; then
    for ws in "${VISIBLE[@]}"; do
        [ "$ws" = "$FOCUSED" ] || i3-msg -q "workspace --no-auto-back-and-forth \"$ws\""
    done
    [ -n "$FOCUSED" ] && i3-msg -q "workspace --no-auto-back-and-forth \"$FOCUSED\""
fi
exit 0
