#!/usr/bin/env bash
# ==========================================
# UI Scale (browser-style zoom for the whole desktop)
# ==========================================
# ui-scale.sh up | down     $mod+Shift+plus / $mod+Shift+minus: 10% bigger / smaller (50-250%)
# ui-scale.sh reset         $mod+Shift+BackSpace: back to 100%
# ui-scale.sh apply         Re-apply the saved scale at login (run from i3/config)
# ui-scale.sh files         Only (re)write the generated snippets (polybar/launch.sh, setup.sh)
# ui-scale.sh status        Print the current scale in %
#
# 100% is exactly the look without this script. How each part is scaled:
#   Xft.dpi = base x scale   i3 (fonts + borders), kitty, dunst, GTK apps, Thorium.
#                            base = Xft.dpi from ~/.Xresources (machine-specific), else 96.
#   own dpi = 96 x scale     Rofi and Polybar ignore Xft.dpi and always render at 96 dpi, so they
#                            get ~/.cache/theme/ui-scale.rasi and ui-scale.ini (+ Polybar height).
# i3, Polybar, Rofi, dunst and open kitty windows follow immediately; apps that read the DPI
# only at startup (Thorium, GTK apps) pick it up when they are reopened.

set -u

CACHE_DIR="$HOME/.cache/theme"
SCALE_FILE="$CACHE_DIR/ui-scale"
STEP=10 MIN=50 MAX=250
BAR_HEIGHT=27   # Polybar height at 100%

mkdir -p "$CACHE_DIR"
scale=$(cat "$SCALE_FILE" 2>/dev/null)
[[ "$scale" =~ ^[0-9]+$ ]] || scale=100

# round(value x scale%)
pct() { echo $(( ($1 * scale + 50) / 100 )); }

base_dpi() {
    local d
    d=$(sed -nE 's/^[[:space:]]*Xft\.dpi:[[:space:]]*([0-9]+).*/\1/p' "$HOME/.Xresources" 2>/dev/null | tail -n 1)
    echo "${d:-96}"
}

write_files() {
    printf '/* Generated by scripts/ui-scale.sh (%s%%) */\nconfiguration { dpi: %s; }\n' \
        "$scale" "$(pct 96)" > "$CACHE_DIR/ui-scale.rasi"
    printf '; Generated by scripts/ui-scale.sh (%s%%)\n[ui-scale]\ndpi = %s\nheight = %s\n' \
        "$scale" "$(pct 96)" "$(pct "$BAR_HEIGHT")" > "$CACHE_DIR/ui-scale.ini"
}

set_xft_dpi() {
    echo "Xft.dpi: $(pct "$(base_dpi)")" | xrdb -merge
}

find_i3() {
    export DISPLAY="${DISPLAY:-:0}"
    if [ -z "${I3SOCK:-}" ]; then
        I3SOCK=$(ls "/run/user/$(id -u)/i3/"ipc-socket.* 2>/dev/null | head -n 1)
        [ -n "$I3SOCK" ] && export I3SOCK
    fi
}

# Live reload: i3 restarts in place (keeps windows, re-reads Xft.dpi, relaunches Polybar via
# exec_always); dunst restarts with the next notification, keeping silent mode as it was.
reload() {
    local paused
    paused=$(dunstctl is-paused 2>/dev/null || echo false)
    pkill -x dunst 2>/dev/null
    i3-msg restart >/dev/null 2>&1
    notify-send -a "Display" -u low -h string:x-dunst-stack-tag:ui-scale \
        "UI scale: $scale%" "Reopen Thorium and GTK apps to resize them too" 2>/dev/null
    [ "$paused" = true ] && dunstctl set-paused true 2>/dev/null
}

case "${1:-status}" in
    up|down|reset)
        find_i3
        # Serialize quick repeated key presses
        exec 9>"$CACHE_DIR/.ui-scale.lock"
        flock 9
        scale=$(cat "$SCALE_FILE" 2>/dev/null)
        [[ "$scale" =~ ^[0-9]+$ ]] || scale=100
        case "$1" in
            up)    scale=$(( scale + STEP )) ;;
            down)  scale=$(( scale - STEP )) ;;
            reset) scale=100 ;;
        esac
        [ "$scale" -gt "$MAX" ] && scale=$MAX
        [ "$scale" -lt "$MIN" ] && scale=$MIN
        echo "$scale" > "$SCALE_FILE"
        write_files
        set_xft_dpi
        reload
        ;;
    apply)
        # Login: ~/.Xresources first (base DPI), then the scaled DPI on top
        find_i3
        [ -f "$HOME/.Xresources" ] && xrdb -merge "$HOME/.Xresources"
        write_files
        set_xft_dpi
        # i3 read Xft.dpi before this ran: restart it in place when the scale is not 100%
        [ "$scale" != 100 ] && i3-msg restart >/dev/null 2>&1
        ;;
    files)  write_files ;;
    status) echo "$scale%" ;;
    *) echo "Usage: $0 up|down|reset|apply|files|status" >&2; exit 1 ;;
esac
exit 0
