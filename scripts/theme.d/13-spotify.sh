# shellcheck shell=bash disable=SC2154  # variables come from apply-theme.sh and the earlier parts
# scripts/theme.d/13-spotify.sh: part of apply-theme.sh, sourced in order in the same shell (not run on its own)
# ==========================================
# 13. Spotify via Spicetify (~/.config/spicetify/Themes/ColorEngine)
# ==========================================
SPICETIFY_BIN=$(command -v spicetify 2>/dev/null || true)
[ -z "$SPICETIFY_BIN" ] && [ -x "$HOME/.spicetify/spicetify" ] && SPICETIFY_BIN="$HOME/.spicetify/spicetify"

if [ -n "$SPICETIFY_BIN" ]; then
    SPICE_THEME_DIR="$HOME/.config/spicetify/Themes/ColorEngine"
    mkdir -p "$SPICE_THEME_DIR"

    # Spicetify color.ini expects hex values without the leading '#'
    cat <<EOF > "$SPICE_THEME_DIR/color.ini"
; Generated by apply-theme.sh (Dotfiles Color Engine)
[base]
text               = ${FG#\#}
subtext            = ${FG_MUTED#\#}
main               = ${BG#\#}
main-elevated      = ${BG_ALT#\#}
highlight          = ${BG_VISUAL#\#}
highlight-elevated = ${BG_VISUAL#\#}
sidebar            = ${BG#\#}
player             = ${BG_ALT#\#}
card               = ${BG_ALT#\#}
shadow             = 000000
selected-row       = ${FG#\#}
button             = ${ACCENT#\#}
button-active      = ${ACCENT_SOFT#\#}
button-secondary   = ${FG_MUTED#\#}
button-disabled    = ${FG_MUTED#\#}
tab-active         = ${BG_VISUAL#\#}
notification       = ${ACCENT#\#}
notification-error = ${ANSI_RED#\#}
misc               = ${ACCENT_DIM#\#}
EOF

    cat <<EOF > "$SPICE_THEME_DIR/user.css"
/* Generated by apply-theme.sh (Dotfiles Color Engine) */
:root {
    --font-family: "$FONT_UI", sans-serif;
    --encore-body-font-stack: "$FONT_UI", sans-serif;
    --encore-title-font-stack: "$FONT_UI", sans-serif;
    --encore-variable-font-stack: "$FONT_UI", sans-serif;
}

/* Spotify's own Circular font is set per element; override it everywhere */
body, button, input, textarea, h1, h2, h3, h4, h5, h6, p, span, div, a {
    font-family: "$FONT_UI", sans-serif !important;
}

/* 4px corners to match i3 & picom */
.main-card-card,
.main-trackList-trackListRow,
.Root__nav-bar,
.Root__main-view,
.Root__right-sidebar {
    border-radius: 4px;
}

/* Accent-coloured progress & volume bars */
.progress-bar {
    --fg-color: $ACCENT;
    --bg-color: $BG_VISUAL;
}
EOF

    # A backup made before Spotify's first launch (fresh install via setup.sh) records an empty
    # Spotify version, because spicetify reads it from the prefs file Spotify writes on launch.
    # Every later refresh then fails with "Spotify version and backup version are mismatched".
    # Fill in the version, but only while Spotify is still the patched install from that backup
    # (an apt update restores Apps/xpui.spa; that case is handled by "restore backup apply" below).
    SPICE_CFG=$("$SPICETIFY_BIN" -c 2>/dev/null) || SPICE_CFG=""
    SPOTIFY_VER=$(grep -o 'app.last-launched-version="[^"]*"' "$HOME/.config/spotify/prefs" 2>/dev/null | cut -d'"' -f2) || SPOTIFY_VER=""
    if [ -f "$SPICE_CFG" ] && [ -n "$SPOTIFY_VER" ] && grep -q '^version *= *$' "$SPICE_CFG" \
        && [ -f "$HOME/.local/state/spicetify/Backup/xpui.spa" ] && [ ! -e /usr/share/spotify/Apps/xpui.spa ]; then
        sed -i "s/^version *= *\$/version = $SPOTIFY_VER/" "$SPICE_CFG"
    fi

    {
        "$SPICETIFY_BIN" -q -n config current_theme ColorEngine color_scheme base inject_css 1 replace_colors 1 \
            && { "$SPICETIFY_BIN" -q -n refresh \
                 || "$SPICETIFY_BIN" -q -n backup apply \
                 || "$SPICETIFY_BIN" -q -n restore backup apply; }
    } </dev/null >/dev/null 2>&1 \
        && SPICE_APPLIED=1 \
        || echo "[!] Spicetify could not apply the theme to Spotify (run 'spicetify backup apply' manually)." >&2

    # Spotify only loads the theme at startup: restart it if it's running. When it was playing, the
    # same track continues at the same position (scripts/spotify-restart.sh, in the background so
    # the theme switch doesn't wait for it)
    if [ "${SPICE_APPLIED:-0}" = 1 ] && pgrep -x spotify >/dev/null; then
        setsid "$DOTFILES_DIR/scripts/spotify-restart.sh" >/dev/null 2>&1 </dev/null &
    fi
fi

